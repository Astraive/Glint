#!/usr/bin/env python3
"""SPK-008: writes the repository-owned synthetic probe images.

Provenance: generated by this script, MIT like the rest of the repository; no
third-party artwork. Each image is 16x16 with four 8x8 quadrants whose colours
the page samples after decoding (see QUADRANTS in src/probes/images.ts):

    top-left  opaque red      top-right    opaque green
    bottom-left opaque white  bottom-right blue at alpha 128

Requires Pillow with WebP and AVIF support (Pillow 11.3+). Run from
spikes/webview2-baseline/web:  python scripts/generate-images.py
"""
from __future__ import annotations

from pathlib import Path

from PIL import Image, features

SIZE = 16
HALF = SIZE // 2
COLOURS = {
    (0, 0): (255, 0, 0, 255),
    (1, 0): (0, 255, 0, 255),
    (0, 1): (255, 255, 255, 255),
    (1, 1): (0, 0, 255, 128),
}
OUT = Path(__file__).resolve().parents[2] / "assets" / "img"


def quadrants() -> Image.Image:
    image = Image.new("RGBA", (SIZE, SIZE))
    for (qx, qy), colour in COLOURS.items():
        for y in range(qy * HALF, (qy + 1) * HALF):
            for x in range(qx * HALF, (qx + 1) * HALF):
                image.putpixel((x, y), colour)
    return image


def svg() -> str:
    rects = []
    for (qx, qy), (r, g, b, a) in COLOURS.items():
        opacity = "" if a == 255 else f' fill-opacity="{a / 255:.4f}"'
        rects.append(
            f'  <rect x="{qx * HALF}" y="{qy * HALF}" width="{HALF}" height="{HALF}" '
            f'fill="rgb({r},{g},{b})"{opacity}/>'
        )
    body = "\n".join(rects)
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{SIZE}" height="{SIZE}" '
        f'viewBox="0 0 {SIZE} {SIZE}" shape-rendering="crispEdges">\n{body}\n</svg>\n'
    )


def main() -> None:
    for name in ("webp", "avif"):
        if not features.check(name):
            raise SystemExit(f"Pillow was built without {name} support")
    OUT.mkdir(parents=True, exist_ok=True)
    image = quadrants()
    # optimize=False keeps the PNG byte-stable across zlib builds of one Pillow.
    image.save(OUT / "probe.png", format="PNG", optimize=False)
    image.save(OUT / "probe.webp", format="WEBP", lossless=True, quality=100, method=6)
    # AVIF is lossy-only in practice; 4:4:4 at max quality keeps flat colours
    # within the page's tolerance.
    image.save(OUT / "probe.avif", format="AVIF", quality=100, subsampling="4:4:4")
    (OUT / "probe.svg").write_text(svg(), encoding="utf-8", newline="\n")
    for path in sorted(OUT.iterdir()):
        print(f"{path.name}: {path.stat().st_size} bytes")


if __name__ == "__main__":
    main()
